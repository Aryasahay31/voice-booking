"""Storage for services, appointments and callbacks.

Two engines, same code:
  - DATABASE_URL set (e.g. Neon)  -> PostgreSQL   (used in the cloud)
  - DATABASE_URL not set          -> SQLite file  (used on your laptop)

Queries in main.py are written once with "?" placeholders; for Postgres they are
converted to "%s" here, so main.py doesn't need to know which engine is running.
"""
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
ENGINE = "postgres" if DATABASE_URL else "sqlite"
DB_PATH = Path(__file__).parent / "salon.db"

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS services (
    id           INTEGER PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    duration_min INTEGER NOT NULL,
    price        INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS appointments (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    service_id    INTEGER NOT NULL REFERENCES services(id),
    customer_name TEXT NOT NULL,
    phone         TEXT NOT NULL,
    start_time    TEXT NOT NULL,   -- local time, 'YYYY-MM-DDTHH:MM'
    end_time      TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'booked',  -- booked | cancelled
    created_at    TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS callback_requests (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    customer_name TEXT NOT NULL,
    phone         TEXT NOT NULL,
    reason        TEXT NOT NULL,
    urgency       TEXT NOT NULL DEFAULT 'normal',  -- normal | urgent
    status        TEXT NOT NULL DEFAULT 'open',    -- open | done
    created_at    TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_appt_time  ON appointments(start_time);
CREATE INDEX IF NOT EXISTS idx_appt_phone ON appointments(phone);
"""

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS services (
    id           INTEGER PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    duration_min INTEGER NOT NULL,
    price        INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS appointments (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id    INTEGER NOT NULL REFERENCES services(id),
    customer_name TEXT NOT NULL,
    phone         TEXT NOT NULL,
    start_time    TEXT NOT NULL,
    end_time      TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'booked',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS callback_requests (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    phone         TEXT NOT NULL,
    reason        TEXT NOT NULL,
    urgency       TEXT NOT NULL DEFAULT 'normal',
    status        TEXT NOT NULL DEFAULT 'open',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_appt_time  ON appointments(start_time);
CREATE INDEX IF NOT EXISTS idx_appt_phone ON appointments(phone);
"""

SEED_SERVICES = [
    (1, "Haircut", 30, 500),
    (2, "Hair Colour", 90, 2500),
    (3, "Beard Trim", 15, 200),
    (4, "Facial", 60, 1200),
    (5, "Manicure", 45, 700),
]


class _PostgresConn:
    """Makes a psycopg connection accept the same '?' queries as SQLite."""

    def __init__(self, raw) -> None:
        self.raw = raw

    def execute(self, sql: str, params=()):
        return self.raw.execute(sql.replace("?", "%s"), params)

    def executemany(self, sql: str, rows) -> None:
        with self.raw.cursor() as cur:
            cur.executemany(sql.replace("?", "%s"), rows)

    def close(self) -> None:
        self.raw.close()


@contextmanager
def connect():
    if ENGINE == "postgres":
        import psycopg
        from psycopg.rows import dict_row

        # autocommit + explicit BEGIN in transaction(), same model as the SQLite side.
        raw = psycopg.connect(DATABASE_URL, autocommit=True, row_factory=dict_row)
        conn = _PostgresConn(raw)
    else:
        # isolation_level=None -> we control transactions explicitly (see transaction())
        conn = sqlite3.connect(DB_PATH, isolation_level=None)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
    finally:
        conn.close()


@contextmanager
def transaction(conn):
    """Make "check the slot is free, then insert" atomic, so two callers can't grab the
    same slot at the same moment.
    SQLite: BEGIN IMMEDIATE takes the write lock up front.
    Postgres: lock the appointments table for writes until the transaction ends."""
    if ENGINE == "postgres":
        conn.execute("BEGIN")
        conn.execute("LOCK TABLE appointments IN SHARE ROW EXCLUSIVE MODE")
    else:
        conn.execute("BEGIN IMMEDIATE")
    try:
        yield
        conn.execute("COMMIT")
    except BaseException:
        conn.execute("ROLLBACK")
        raise


def init() -> None:
    with connect() as conn:
        if ENGINE == "postgres":
            conn.raw.execute(POSTGRES_SCHEMA)  # psycopg runs multiple statements without params
        else:
            conn.executescript(SQLITE_SCHEMA)
        if conn.execute("SELECT COUNT(*) AS n FROM services").fetchone()["n"] == 0:
            conn.executemany(
                "INSERT INTO services (id, name, duration_min, price) VALUES (?, ?, ?, ?)",
                SEED_SERVICES,
            )